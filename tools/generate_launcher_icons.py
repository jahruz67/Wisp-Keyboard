"""Regenerate the simple keyboard launcher mark. Requires Pillow; does not build the app."""

from pathlib import Path

from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[1]
BACKGROUND = "#080F2D"
FOREGROUND = "#EAF4FF"
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
BODY = (25, 37, 83, 73)
KEYS = [(x, y, x + 5, y + 4) for y in (45, 53) for x in (33, 41, 49, 57, 65, 73)]
KEYS.append((41, 63, 67, 66))


def rounded_path(bounds, radius):
    left, top, right, bottom = bounds
    return (
        f"M{left + radius},{top} H{right - radius} "
        f"Q{right},{top} {right},{top + radius} V{bottom - radius} "
        f"Q{right},{bottom} {right - radius},{bottom} H{left + radius} "
        f"Q{left},{bottom} {left},{bottom - radius} V{top + radius} "
        f"Q{left},{top} {left + radius},{top} Z"
    )


def write_vectors():
    keys = " ".join(rounded_path(bounds, 0.75) for bounds in KEYS)
    vector = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_launcher_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="@android:color/transparent"
        android:strokeColor="{FOREGROUND}"
        android:strokeWidth="3"
        android:pathData="{rounded_path(BODY, 7)}" />
    <path android:fillColor="{FOREGROUND}" android:pathData="{keys}" />
</vector>
'''
    for resources in (ROOT / "java/res", ROOT / "java/unstable/res"):
        (resources / "drawable/ic_launcher_foreground.xml").write_text(vector, encoding="utf-8")
    (ROOT / "java/unstable/res/drawable/ic_launcher_background.xml").write_text(
        f'''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{BACKGROUND}" android:pathData="M0,0h108v108h-108z" />
</vector>
''', encoding="utf-8")


def render_icon(size, circular=False):
    # Legacy launchers display the complete bitmap, so render the adaptive icon's central 72dp.
    scale = size * 4 / 72
    canvas_size = size * 4
    image = Image.new("RGBA", (canvas_size, canvas_size))
    draw = ImageDraw.Draw(image)
    if circular:
        draw.ellipse((0, 0, canvas_size - 1, canvas_size - 1), fill=BACKGROUND)
    else:
        draw.rounded_rectangle((0, 0, canvas_size - 1, canvas_size - 1), radius=12 * scale, fill=BACKGROUND)

    def box(bounds):
        return tuple((value - 18) * scale for value in bounds)

    # Match the vector's centered 3dp border.
    draw.rounded_rectangle(box((23.5, 35.5, 84.5, 74.5)), radius=8.5 * scale, fill=FOREGROUND)
    draw.rounded_rectangle(box((26.5, 38.5, 81.5, 71.5)), radius=5.5 * scale, fill=BACKGROUND)
    for bounds in KEYS:
        draw.rounded_rectangle(box(bounds), radius=0.75 * scale, fill=FOREGROUND)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def main():
    write_vectors()
    for density, size in DENSITIES.items():
        for suffix, circular in (("", False), ("_round", True)):
            icon = render_icon(size, circular)
            icon.save(ROOT / f"java/res/mipmap-{density}/ic_launcher{suffix}.png")
            icon.save(ROOT / f"java/unstable/res/mipmap-{density}/ic_launcher{suffix}.webp", lossless=True)
    render_icon(512).save(ROOT / "website/assets/wisp-icon.png")
    print("Updated adaptive, monochrome, legacy, round, unstable, and website icons.")


if __name__ == "__main__":
    main()
